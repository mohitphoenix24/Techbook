/* ==========================================================================
   Source explorer: #/code (all projects) and #/code/<project>[/<file path>]
   Reads window.PROJECT_CODE (generated by build.py from code/) and window.COURSE.
   Loads BEFORE app.js, which calls EXT.pages.code(parts, anchor, api).
   ========================================================================== */
(function () {
  "use strict";
  const EXT = window.EXT || (window.EXT = {});
  EXT.icons = Object.assign(EXT.icons || {}, {
    folder: '<path d="M3 7a2 2 0 0 1 2-2h4l2 2h8a2 2 0 0 1 2 2v8a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2z"/>',
    download: '<path d="M12 3v12"/><path d="m7 11 5 5 5-5"/><path d="M5 21h14"/>',
    fileCode: '<path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><path d="M14 2v6h6"/><path d="m10 13-2 2 2 2M14 13l2 2-2 2"/>',
  });

  const KINDS = { backend: "FastAPI backend", frontend: "React frontend" };

  function metaFor(slug) {
    const mod = (window.COURSE.modules || []).find((m) => m.project === slug);
    return { module: mod, title: mod ? mod.title : slug, level: mod ? mod.level : "mixed", summary: mod ? mod.description : "" };
  }

  function tree(files) {
    const root = { dirs: {}, files: [] };
    files.forEach((f) => {
      const parts = f.path.split("/");
      let node = root;
      parts.slice(0, -1).forEach((d) => { node = node.dirs[d] || (node.dirs[d] = { dirs: {}, files: [] }); });
      node.files.push({ name: parts[parts.length - 1], file: f });
    });
    return root;
  }

  function drawTree(api, node, slug, active, depth = 0, prefix = "") {
    const { esc, icon } = api;
    const dirs = Object.keys(node.dirs).sort();
    const open = (name) => active && active.startsWith(prefix + name + "/") || depth < 2;
    return dirs.map((d) => `<details class="ex-dir" ${open(d) ? "open" : ""}><summary style="padding-left:${8 + depth * 14}px">${icon("folder")}<span>${esc(d)}</span></summary>${drawTree(api, node.dirs[d], slug, active, depth + 1, prefix + d + "/")}</details>`).join("")
      + node.files.sort((a, b) => a.name.localeCompare(b.name)).map((x) =>
        `<a class="ex-file ${x.file.path === active ? "on" : ""}" style="padding-left:${22 + depth * 14}px" href="#/code/${esc(slug)}/${esc(x.file.path)}">${icon("fileCode")}<span>${esc(x.name)}</span></a>`).join("");
  }

  function renderIndex(api) {
    const { main, esc, icon, lvlChip, setLayout, setActiveNav } = api;
    setLayout({ sidebar: false });
    setActiveNav("code");
    document.title = `Source code — ${api.SITE.name}`;
    const cards = Object.keys(window.PROJECT_CODE).map((slug) => {
      const m = metaFor(slug), files = window.PROJECT_CODE[slug].files;
      const lines = files.reduce((n, f) => n + f.text.split("\n").length, 0);
      return `<a class="proj-card" href="#/code/${esc(slug)}"><div class="proj-cover" style="background:linear-gradient(135deg,var(--accent),var(--accent-2))">${icon("code")}</div>
        <div class="proj-body"><h3>${esc(m.title)}</h3><p>${esc(m.summary)}</p><div class="tags">${lvlChip(m.level)}<span class="tag">${files.length} files</span><span class="tag">${lines.toLocaleString()} lines</span></div></div></a>`;
    }).join("");
    main.innerHTML = `<div class="wide"><div class="page-hero"><div class="kicker">Source code</div><h1>Every project, complete</h1>
      <p>The lessons quote this code, and every project has passing tests. Browse it here, copy a file, or download the whole project as a zip and run it on your computer.</p></div>
      <div class="projects-grid">${cards}</div></div>`;
  }

  function renderProject(api, slug, path) {
    const { main, esc, icon, lvlChip, setLayout, setActiveNav, highlight, copyText, $, $$ } = api;
    const data = window.PROJECT_CODE[slug];
    if (!data) return renderIndex(api);
    setLayout({ sidebar: false });
    setActiveNav("code");
    const m = metaFor(slug);
    const files = data.files;
    const first = files.find((f) => /(^|\/)README\.md$/.test(f.path) && f.path.split("/").length === 1) || files[0];
    const file = files.find((f) => f.path === path) || first;
    document.title = `${file.path} — ${m.title} — ${api.SITE.name}`;
    const lines = file.text.split("\n");
    const start = m.module && m.module.lessons[0];
    main.innerHTML = `<div class="ex">
      <div class="ex-head"><div><div class="kicker">Source code</div><h1>${esc(m.title)}</h1><p>${esc(m.summary)}</p></div>
        <div class="ex-actions">${lvlChip(m.level)}
          <a class="btn primary" href="downloads/${esc(slug)}.zip" download>${icon("download")} Download zip</a>
          ${start ? `<a class="btn" href="#/l/${esc(start.id)}">${icon("book")} Read the lessons</a>` : ""}
          <a class="btn" href="#/code">All projects</a></div></div>
      <div class="ex-body">
        <nav class="ex-tree" aria-label="Files">${drawTree(api, tree(files), slug, file.path)}</nav>
        <section class="ex-view"><div class="ex-bar"><span class="ex-path">${icon("fileCode")} ${esc(file.path)}</span><span class="ex-meta">${lines.length} lines</span>
          <button class="btn ghost" id="ex-copy">${icon("copy")}<span class="lbl-sm">Copy</span></button></div>
          <div class="ex-code">${file.lang === "md" ? `<div class="ex-md prose">${api.md(file.text)}</div>` : `<pre class="ex-ln" aria-hidden="true">${lines.map((_, i) => i + 1).join("\n")}</pre><pre class="ex-src"><code>${highlight(file.text, file.lang)}</code></pre>`}</div></section>
      </div></div>`;
    $("#ex-copy").onclick = () => copyText(file.text);
    const on = $(".ex-file.on");
    if (on) on.scrollIntoView({ block: "nearest" });
  }

  EXT.pages = Object.assign(EXT.pages || {}, {
    code(parts, anchor, api) {
      if (!parts.length) return renderIndex(api);
      renderProject(api, parts[0], parts.slice(1).join("/"));
    },
  });
  EXT.search = (terms) => {
    const hits = [];
    Object.keys(window.PROJECT_CODE || {}).forEach((slug) => {
      window.PROJECT_CODE[slug].files.forEach((f) => {
        if (hits.length < 8 && terms.every((t) => f.path.toLowerCase().includes(t))) hits.push({ title: f.path.split("/").pop(), sub: `${metaFor(slug).title} · ${f.path}`, href: `#/code/${slug}/${f.path}`, icon: "fileCode" });
      });
    });
    return hits;
  };
  EXT.searchLabel = "Source files";
})();

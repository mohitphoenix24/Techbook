/* ==========================================================================
   GenLab simulators, part 7: generative media.
   diffusion  (a real diffusion sampler on a 2-D dataset, using the exact denoiser of the empirical distribution)
   ========================================================================== */
(function () {
  "use strict";
  const { sim, el, esc, $, $$, clamp, UI } = window.VIZ.SIM;
  const { ctrl, pct, mulberry32 } = window.VIZ.SIM.gl;

  // the "data distribution": a smiley made of points in [-1, 1]²
  function makeData() {
    const pts = [], rnd = mulberry32(11);
    for (let i = 0; i < 90; i++) { const a = (i / 90) * 2 * Math.PI; pts.push([0.9 * Math.cos(a), 0.9 * Math.sin(a)]); }                                    // face outline
    for (let i = 0; i < 14; i++) { const a = (i / 14) * 2 * Math.PI; pts.push([-0.33 + 0.07 * Math.cos(a), 0.3 + 0.07 * Math.sin(a)], [0.33 + 0.07 * Math.cos(a), 0.3 + 0.07 * Math.sin(a)]); }   // eyes
    for (let i = 0; i <= 40; i++) { const a = Math.PI * (1.12 + (0.76 * i) / 40); pts.push([0.52 * Math.cos(a), 0.52 * Math.sin(a) + 0.02]); }                  // smile
    return pts;
  }
  const DATA = makeData();
  const abar = (t) => Math.pow(Math.cos(((t + 0.008) / 1.008) * Math.PI / 2), 2);        // cosine noise schedule: fraction of signal left at time t in [0,1]
  const gauss = (rnd) => Math.sqrt(-2 * Math.log(Math.max(1e-9, rnd()))) * Math.cos(2 * Math.PI * rnd());

  // E[x0 | x_t]: the best possible denoiser for the empirical distribution (a Gaussian-weighted average of the data points)
  function posteriorMean(x, y, ab) {
    const s = Math.sqrt(ab), v = Math.max(1 - ab, 1e-4); let wsum = 0, mx = 0, my = 0;
    const logs = DATA.map(([dx, dy]) => -((x - s * dx) ** 2 + (y - s * dy) ** 2) / (2 * v));
    const m = Math.max(...logs);
    DATA.forEach(([dx, dy], i) => { const w = Math.exp(logs[i] - m); wsum += w; mx += w * dx; my += w * dy; });
    return [mx / wsum, my / wsum];
  }

  sim("diffusion", "Diffusion in 2-D", "ai", (body) => {
    const N = 260, st = { t: 0.5, steps: 20, samples: null, seed: 1 };
    const c = ctrl(`<label>Noise level (forward) <input type="range" min="0" max="1" step="0.02" value="${st.t}" data-k="t"><output>0.50</output></label>
      <label>Sampling steps <input type="range" min="2" max="60" value="${st.steps}" data-k="steps"><output>${st.steps}</output></label>
      <button class="sd-btn primary" data-a="gen">Generate ${N} new points</button><button class="sd-btn" data-a="clear">${UI.reset} Clear</button>`);
    body.appendChild(c);
    const stage = el(`<div class="sd-stage gl-diff"></div>`);
    body.appendChild(stage);
    body.appendChild(el(`<div class="sd-note-line"><b>Left:</b> the training data (a smiley). <b>Middle:</b> the same points after the forward process adds noise (slide the noise level: signal fades into pure noise). <b>Right:</b> new points generated by starting from pure noise and repeatedly denoising (DDIM steps). Fewer steps give blurrier results. This toy uses the exact denoiser for these data points, so it reproduces the data; real models learn a neural network that generalises.</div>`));
    const W = 260, H = 260;
    const sx = (v) => ((v + 1.5) / 3) * W, sy = (v) => H - ((v + 1.5) / 3) * H;
    const dots = (pts, col, r = 2.4, op = 0.85) => pts.map(([x, y]) => `<circle cx="${sx(x).toFixed(1)}" cy="${sy(y).toFixed(1)}" r="${r}" fill="${col}" opacity="${op}"/>`).join("");
    const panel = (title, inner) => `<div class="gl-dpanel"><div class="gl-label"><b>${title}</b></div><svg viewBox="0 0 ${W} ${H}" class="gl-dsvg"><rect width="${W}" height="${H}" rx="10" class="bg"/>${inner}</svg></div>`;
    const noised = () => {
      const rnd = mulberry32(5), ab = abar(st.t), s = Math.sqrt(ab), n = Math.sqrt(1 - ab);
      return DATA.map(([x, y]) => [s * x + n * gauss(rnd), s * y + n * gauss(rnd)]);
    };
    const generate = () => {
      const rnd = mulberry32(100 + st.seed++), S = st.steps, pts = [];
      for (let i = 0; i < N; i++) {
        let x = gauss(rnd), y = gauss(rnd);                                   // start from pure noise
        for (let k = S; k >= 1; k--) {
          const tCur = k / S, tNext = (k - 1) / S, abC = abar(tCur), abN = abar(tNext);
          const [x0, y0] = posteriorMean(x, y, abC);                          // predict the clean point
          const ex = (x - Math.sqrt(abC) * x0) / Math.sqrt(1 - abC), ey = (y - Math.sqrt(abC) * y0) / Math.sqrt(1 - abC);   // implied noise
          x = Math.sqrt(abN) * x0 + Math.sqrt(1 - abN) * ex; y = Math.sqrt(abN) * y0 + Math.sqrt(1 - abN) * ey;
        }
        pts.push([x, y]);
      }
      st.samples = pts;
    };
    const draw = () => {
      const near = st.samples ? st.samples.map(([x, y]) => Math.min(...DATA.map(([dx, dy]) => Math.hypot(x - dx, y - dy)))) : null;
      const avg = near ? near.reduce((a, b) => a + b, 0) / near.length : 0;
      stage.innerHTML = panel("Training data", dots(DATA, "var(--n3)")) + panel(`Noised (signal left ${pct(abar(st.t), 0)})`, dots(noised(), "var(--n7)", 2.4, 0.8)) +
        panel(st.samples ? `Generated in ${st.steps} steps` : "Generated (press the button)", st.samples ? dots(st.samples, "var(--n5)", 2.2, 0.8) : `<text x="${W / 2}" y="${H / 2}" text-anchor="middle" class="hint">starts from pure noise</text>`) +
        (near ? `<div class="gl-diff-stat" style="grid-column:1/-1">Average distance from a generated point to the nearest real point: <b>${avg.toFixed(3)}</b> ${avg < 0.03 ? "(sharp)" : avg < 0.08 ? "(a little blurry)" : "(blurry: too few steps)"}</div>` : "");
    };
    $('[data-k="t"]', c).oninput = (e) => { st.t = +e.target.value; e.target.nextElementSibling.textContent = st.t.toFixed(2); draw(); };
    $('[data-k="steps"]', c).oninput = (e) => { st.steps = +e.target.value; e.target.nextElementSibling.textContent = st.steps; st.samples = null; draw(); };
    $('[data-a="gen"]', c).onclick = () => { generate(); draw(); };
    $('[data-a="clear"]', c).onclick = () => { st.samples = null; draw(); };
    draw();
  });
})();

/* ==========================================================================
   Site home page — the course catalogue.
   Reads window.PLATFORM + window.COURSES (courses.js) and window.COURSE_STATS
   (stats.js, generated by build.py). Progress comes from each course's
   localStorage keys ("<storageKey>:progress", ":last", ":lastTitle", ":visited").
   ========================================================================== */
(function () {
  "use strict";

  const PLATFORM = window.PLATFORM || { name: "Courses" };
  const COURSES = window.COURSES || [];
  const STATS = window.COURSE_STATS || {};
  const THEME_KEY = "techcontent:theme";

  const $ = (sel) => document.querySelector(sel);
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const read = (key, d) => { try { const v = localStorage.getItem(key); return v == null ? d : JSON.parse(v); } catch { return d; } };

  const ICONS = {
    play: '<polygon points="6 3 20 12 6 21 6 3"/>',
    sun: '<circle cx="12" cy="12" r="4"/><path d="M12 2v2M12 20v2M4.93 4.93l1.41 1.41M17.66 17.66l1.41 1.41M2 12h2M20 12h2M6.34 17.66l-1.41 1.41M19.07 4.93l-1.41 1.41"/>',
    moon: '<path d="M12 3a6 6 0 0 0 9 9 9 9 0 1 1-9-9Z"/>',
    book: '<path d="M2 3h6a4 4 0 0 1 4 4v14a3 3 0 0 0-3-3H2z"/><path d="M22 3h-6a4 4 0 0 0-4 4v14a3 3 0 0 1 3-3h7z"/>',
    sparkles: '<path d="M12 3l1.9 5.8L20 11l-6.1 2.2L12 19l-1.9-5.8L4 11l6.1-2.2z"/><path d="M19 3v4M17 5h4"/>',
    flask: '<path d="M9 3h6M10 3v6.5L4.5 19a1.5 1.5 0 0 0 1.3 2h12.4a1.5 1.5 0 0 0 1.3-2L14 9.5V3"/><path d="M7 15h10"/>',
    right: '<path d="M5 12h14"/><path d="m12 5 7 7-7 7"/>',
    terminal: '<path d="m4 17 6-6-6-6"/><path d="M12 19h8"/>',
    layers: '<path d="m12 2 10 5-10 5L2 7z"/><path d="m2 17 10 5 10-5"/><path d="m2 12 10 5 10-5"/>',
    rocket: '<path d="M4.5 16.5c-1.5 1.26-2 5-2 5s3.74-.5 5-2c.71-.84.7-2.13-.09-2.91a2.18 2.18 0 0 0-2.91-.09z"/><path d="m12 15-3-3a22 22 0 0 1 2-3.95A12.88 12.88 0 0 1 22 2c0 2.72-.78 7.5-6 11a22.35 22.35 0 0 1-4 2z"/><path d="M9 12H4s.55-3.03 2-4c1.62-1.08 5 0 5 0"/><path d="M12 15v5s3.03-.55 4-2c1.08-1.62 0-5 0-5"/>',
    zap: '<path d="M13 2 3 14h9l-1 8 10-12h-9l1-8z"/>',
    cap: '<path d="M22 10 12 5 2 10l10 5 10-5z"/><path d="M6 12v5c3 3 9 3 12 0v-5"/>',
    atom: '<circle cx="12" cy="12" r="1"/><path d="M20.2 20.2c2.04-2.03.02-7.36-4.5-11.9-4.54-4.52-9.87-6.54-11.9-4.5-2.04 2.03-.02 7.36 4.5 11.9 4.54 4.52 9.87 6.54 11.9 4.5Z"/><path d="M15.7 15.7c4.52-4.54 6.54-9.87 4.5-11.9-2.03-2.04-7.36-.02-11.9 4.5-4.52 4.54-6.54 9.87-4.5 11.9 2.03 2.04 7.36.02 11.9-4.5Z"/>',
    grid: '<rect x="3" y="3" width="18" height="18" rx="2"/><path d="M3 9h18M3 15h18M9 3v18M15 3v18"/>',
    eye: '<path d="M2 12s3-7 10-7 10 7 10 7-3 7-10 7-10-7-10-7Z"/><circle cx="12" cy="12" r="3"/>',
    cube: '<path d="M21 8 12 3 3 8v8l9 5 9-5z"/><path d="m3 8 9 5 9-5M12 13v8"/>',
    network: '<circle cx="5" cy="6" r="2"/><circle cx="5" cy="18" r="2"/><circle cx="19" cy="12" r="2"/><circle cx="12" cy="12" r="2"/><path d="M7 6.5 10.5 11M7 17.5l3.5-4.5M14 12h3"/>',
  };
  const icon = (name) => `<svg class="icon" viewBox="0 0 24 24" aria-hidden="true">${ICONS[name] || ICONS.book}</svg>`;

  /* ------------------------------------------------------------ per-course state */
  const courses = COURSES.map((c) => {
    const s = STATS[c.path] || {};
    const done = Object.keys(read(`${c.storageKey}:progress`, {})).length;
    const total = (s.lessons || 0) + (s.projects || 0);
    return {
      ...c, s, done, total,
      pct: total ? Math.min(100, Math.round((done / total) * 100)) : 0,
      last: read(`${c.storageKey}:last`, null),
      lastTitle: read(`${c.storageKey}:lastTitle`, ""),
      visited: read(`${c.storageKey}:visited`, 0),
      href: `${c.path}/index.html`,
    };
  });
  const sum = (k) => courses.reduce((n, c) => n + (c.s[k] || 0), 0);
  const nf = (n) => n.toLocaleString("en-US");
  const logo = (c) => `<span class="hub-logo" style="--a:${esc(c.colors[0])};--b:${esc(c.colors[1])}">${c.logoIcon ? icon(c.logoIcon) : esc(c.logo)}</span>`;

  function card(c) {
    const resume = c.last ? `${c.href}#/l/${encodeURIComponent(c.last)}` : c.href;
    const third = c.s.problems ? [c.s.problems, "problems"] : [(c.s.projects || 0) + (c.s.apps || 0), "projects"];
    return `<article class="course-card" data-q="${esc([c.name, c.title, c.description, ...(c.topics || [])].join(" ").toLowerCase())}" style="--a:${esc(c.colors[0])};--b:${esc(c.colors[1])}">
      <div class="cc-top">${logo(c)}<div class="cc-name"><h3><a href="${esc(c.href)}">${esc(c.name)}</a></h3><div class="cc-sub">${esc(c.title)}</div></div></div>
      <div class="cc-body">
        <p class="cc-desc">${esc(c.description)}</p>
        <div class="tags">${(c.topics || []).map((t) => `<span class="tag">${esc(t)}</span>`).join("")}</div>
        <div class="cc-stats">
          <div><b>${nf(c.s.lessons || 0)}</b><span>lessons</span></div>
          <div><b>${nf(third[0])}</b><span>${third[1]}</span></div>
          <div><b>${nf(c.s.examples || 0)}</b><span>runnable examples</span></div>
        </div>
        <div class="cc-foot">
          <div class="cc-progress">${c.done ? `${c.done} of ${c.total} done · ${c.pct}%` : "Not started yet"}<div class="bar"><i style="width:${c.pct}%"></i></div></div>
          <a class="btn primary" href="${esc(resume)}">${icon(c.last ? "play" : "rocket")} ${c.last ? "Continue" : "Start course"}</a>
        </div>
      </div>
      <div class="cc-meta"><span>${icon("cap")} ${esc(c.level || "All levels")}</span><span>${icon("terminal")} ${esc(c.runtime || "")}</span></div>
    </article>`;
  }

  /* ------------------------------------------------------------ page */
  function render() {
    document.title = `${PLATFORM.name} — ${PLATFORM.tagline || "Courses"}`;
    $("#brand-name").textContent = PLATFORM.name;
    $("#brand-tag").textContent = PLATFORM.tagline || "";
    const recent = courses.filter((c) => c.last).sort((a, b) => b.visited - a.visited);

    $("#main").innerHTML = `<div class="home hub">
      <section class="hero">
        <div class="hero-bg"><div class="orb a"></div><div class="orb b"></div></div>
        <div>
          <span class="eyebrow"><b>${courses.length} courses</b> ${courses.map((c) => esc(c.name)).join(" · ")}</span>
          <h1>Pick a course. <span class="grad">Learn by running the code.</span></h1>
          <p class="sub">Every course follows the same format: plain-English explanations, clear definitions, examples you can edit and run in the browser, quizzes and complete projects.</p>
          <div class="cta-row">
            <a class="btn btn-lg primary" href="#courses">${icon("layers")} Browse courses</a>
            ${recent.length ? `<a class="btn btn-lg" href="${esc(recent[0].href)}#/l/${encodeURIComponent(recent[0].last)}">${icon("play")} Continue ${esc(recent[0].name)}</a>` : ""}
          </div>
          <div class="hero-note">${icon("zap")} Nothing to install. Your progress is saved in this browser.</div>
        </div>
      </section>

      <section class="stats">
        <div class="stat"><b>${courses.length}</b><span>courses</span></div>
        <div class="stat"><b>${nf(sum("lessons"))}</b><span>in-depth lessons</span></div>
        <div class="stat"><b>${nf(sum("examples"))}+</b><span>runnable code examples</span></div>
        <div class="stat"><b>${nf(sum("projects") + sum("apps"))}</b><span>complete projects</span></div>
      </section>

      ${recent.length ? `<section class="section">
        <div class="section-head"><div><div class="kicker">Pick up where you left off</div><h2>Continue learning</h2></div></div>
        <div class="continue-row">${recent.map((c) => `<a class="continue-card" style="--a:${esc(c.colors[0])};--b:${esc(c.colors[1])}" href="${esc(c.href)}#/l/${encodeURIComponent(c.last)}">${logo(c)}<span class="t"><small>${esc(c.name)} · ${c.pct}% done</small><b>${esc(c.lastTitle || "Resume course")}</b></span><span class="go">${icon("right")}</span></a>`).join("")}</div>
      </section>` : ""}

      <section class="section" id="courses">
        <div class="section-head"><div><div class="kicker">The catalogue</div><h2>All courses</h2>
          <p>Each course is self-contained. Start with any of them; use the <b>Courses</b> menu in the top bar to switch between them at any time.</p></div></div>
        <div class="hub-tools"><input class="gl-input" id="hub-q" placeholder="Filter courses… (e.g. agents, graphs, hooks)" autocomplete="off"><span class="count" id="hub-count"></span></div>
        <div class="course-grid" id="course-grid">${courses.map(card).join("")}</div>
        <div class="hub-empty" id="hub-empty" hidden>No course matches that filter.</div>
      </section>
      <div class="foot-note">${esc(PLATFORM.footer || "")}</div>
    </div>`;

    const q = $("#hub-q");
    const filter = () => {
      const terms = q.value.toLowerCase().split(/\s+/).filter(Boolean);
      let shown = 0;
      document.querySelectorAll(".course-card").forEach((el) => {
        const ok = terms.every((t) => el.dataset.q.includes(t));
        el.hidden = !ok;
        shown += ok;
      });
      $("#hub-count").textContent = terms.length ? `${shown} of ${courses.length}` : "";
      $("#hub-empty").hidden = shown > 0;
    };
    q.addEventListener("input", filter);
  }

  /* ------------------------------------------------------------ theme */
  function applyTheme(t) {
    document.documentElement.setAttribute("data-theme", t);
    $("#theme-btn").innerHTML = icon(t === "dark" ? "sun" : "moon");
    $("#theme-btn").title = t === "dark" ? "Switch to light theme" : "Switch to dark theme";
  }
  $("#theme-btn").onclick = () => {
    const t = document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark";
    try { localStorage.setItem(THEME_KEY, t); } catch { /* ignore */ }
    applyTheme(t);
  };
  applyTheme(document.documentElement.getAttribute("data-theme") || "dark");
  $("#brand-logo").innerHTML = icon("grid");

  render();
  // coming back with the browser's back button can restore a stale page: refresh progress
  window.addEventListener("pageshow", (e) => { if (e.persisted) render(); });
})();

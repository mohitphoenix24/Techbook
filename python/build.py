#!/usr/bin/env python3
"""Bundle the Markdown lessons in content/ into assets/js/content.js.

    python3 build.py           # rebuild the site content
    python3 build.py --test    # also execute every ```python run``` block locally
    python3 build.py --watch   # rebuild whenever a lesson changes

Layout:
    content/<NN-module>/_module.md     front matter: title, icon, level, description, kind
    content/<NN-module>/<NN-slug>.md   front matter: title, level, time, summary (+ tags, icon, cover)
The lesson id is the file name without its number prefix, so keep slugs unique.
"""
import json
import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CONTENT = ROOT / "content"
OUT = ROOT / "assets" / "js" / "content.js"


def parse_front_matter(text: str):
    meta = {}
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            for line in text[3:end].strip().splitlines():
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip()] = v.strip().strip('"')
            text = text[end + 4:].lstrip("\n")
    return meta, text


def strip_number(name: str) -> str:
    return re.sub(r"^\d+[-_]", "", name)


def build():
    modules, ids = [], set()
    for mdir in sorted(p for p in CONTENT.iterdir() if p.is_dir()):
        mod_file = mdir / "_module.md"
        if not mod_file.exists():
            continue
        meta, desc = parse_front_matter(mod_file.read_text(encoding="utf-8"))
        module = {
            "id": strip_number(mdir.name),
            "title": meta.get("title", mdir.name),
            "icon": meta.get("icon", "book"),
            "level": meta.get("level", "mixed"),
            "kind": meta.get("kind", "learn"),
            "description": meta.get("description", desc.strip()),
            "lessons": [],
        }
        for f in sorted(mdir.glob("*.md")):
            if f.name.startswith("_"):
                continue
            lmeta, body = parse_front_matter(f.read_text(encoding="utf-8"))
            lid = strip_number(f.stem)
            if lid in ids:
                raise SystemExit(f"Duplicate lesson id '{lid}' ({f})")
            ids.add(lid)
            lesson = {"id": lid, "title": lmeta.get("title", lid), "body": body}
            for k in ("level", "time", "summary", "tags", "icon", "cover"):
                if k in lmeta:
                    lesson[k] = lmeta[k]
            module["lessons"].append(lesson)
        modules.append(module)

    payload = json.dumps({"modules": modules, "built": time.strftime("%Y-%m-%d %H:%M")}, ensure_ascii=False)
    OUT.write_text(f"/* generated by build.py — edit the Markdown in content/ instead */\nwindow.COURSE = {payload};\n", encoding="utf-8")
    n = sum(len(m["lessons"]) for m in modules)
    print(f"built {OUT.relative_to(ROOT)}: {len(modules)} modules, {n} lessons, {len(payload) // 1024} KB")
    return modules


FENCE = re.compile(r"^(`{3,})python[ \t]*([^\n]*)\n(.*?)^\1\s*$", re.S | re.M)


def meta_flags(meta: str) -> set:
    """Bare words in a fence's meta (quoted titles removed), e.g. {'run', 'skiplocal'}."""
    return set(re.findall(r"[\w-]+", re.sub(r'\w+="[^"]*"', "", meta)))


def test(modules):
    Path(tempfile.gettempdir(), "pg_run").mkdir(exist_ok=True)
    failures, count = [], 0
    for m in modules:
        for lesson in m["lessons"]:
            shared_prefix = ""
            for i, match in enumerate(FENCE.finditer(lesson["body"]), 1):
                code = match.group(3)
                flags = meta_flags(match.group(2))
                if "run" not in flags or "skiplocal" in flags:
                    continue
                if "shared" in flags:                     # project steps build on earlier steps
                    code, shared_prefix = shared_prefix + "\n" + code, shared_prefix + "\n" + code
                count += 1
                with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as fh:
                    fh.write("import matplotlib\nmatplotlib.use('Agg')\n" if "matplotlib" in code else "")
                    fh.write(code)
                    path = fh.name
                try:
                    r = subprocess.run([sys.executable, path], capture_output=True, text=True, timeout=120, input="test\n", cwd=tempfile.gettempdir() + "/pg_run")
                    ok = r.returncode == 0
                    err = r.stderr[-1500:]
                except subprocess.TimeoutExpired:
                    ok, err = False, "timeout"
                expect_error = "expect-error" in flags
                if ok == expect_error:
                    failures.append((lesson["id"], i, err if not expect_error else "expected an error but it ran"))
                    print(f"  ✗ {lesson['id']} block {i}")
    print(f"\nran {count} runnable blocks: {count - len(failures)} passed, {len(failures)} failed")
    for lid, i, err in failures:
        print(f"\n--- {lid} #{i}\n{err}")
    return not failures


if __name__ == "__main__":
    mods = build()
    if "--test" in sys.argv:
        sys.exit(0 if test(mods) else 1)
    if "--watch" in sys.argv:
        stamp = None
        while True:
            s = max(p.stat().st_mtime for p in CONTENT.rglob("*.md"))
            if stamp and s != stamp:
                build()
            stamp = s
            time.sleep(1)

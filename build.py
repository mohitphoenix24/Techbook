#!/usr/bin/env python3
"""Build the whole site: every course listed in courses.js, then the catalogue stats.

    python3 build.py                 # run each course's own build.py, then refresh stats.js
    python3 build.py --stats         # only refresh stats.js from the existing content bundles
    python3 build.py --only=python   # build one course (by its folder), then refresh stats.js
    python3 build.py -- --no-verify  # arguments after "--" are passed to every course build.py

stats.js holds the lesson / project / example counts shown on the site home page.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REGISTRY = ROOT / "courses.js"
STATS = ROOT / "stats.js"
RUN_FENCE = re.compile(r"^`{3,}[\w+-]+[ \t]+[^\n]*\brun\b", re.M)
PROBLEM = re.compile(r"^:::problem\b", re.M)


def course_paths():
    """Folder names of the registered courses, in catalogue order."""
    return re.findall(r'^\s*path:\s*"([^"]+)"', REGISTRY.read_text(encoding="utf-8"), re.M)


def load_bundle(path: str):
    text = (ROOT / path / "assets" / "js" / "content.js").read_text(encoding="utf-8")
    return json.loads(text[text.index("{"): text.rindex("}") + 1])


def stats_for(path: str):
    modules = load_bundle(path)["modules"]
    learn = [m for m in modules if m.get("kind") != "projects"]
    bodies = [l["body"] for m in modules for l in m["lessons"]]
    return {
        "modules": len(learn),
        "lessons": sum(len(m["lessons"]) for m in learn),
        "projects": sum(len(m["lessons"]) for m in modules if m.get("kind") == "projects"),
        "examples": sum(len(RUN_FENCE.findall(b)) for b in bodies),
        "problems": sum(len(PROBLEM.findall(b)) for b in bodies),
    }


def main(argv):
    passthrough = argv[argv.index("--") + 1:] if "--" in argv else []
    own = argv[: argv.index("--")] if "--" in argv else argv
    only = next((a.split("=", 1)[1] for a in own if a.startswith("--only=")), None)
    paths = course_paths()
    missing = [p for p in paths if not (ROOT / p / "index.html").exists()]
    if missing:
        raise SystemExit(f"courses.js lists folders that do not exist: {', '.join(missing)}")

    failed = []
    if "--stats" not in own:
        for p in paths:
            if only and p != only:
                continue
            print(f"\n=== {p}")
            r = subprocess.run([sys.executable, "build.py", *passthrough], cwd=ROOT / p)
            if r.returncode:
                failed.append(p)

    stats = {p: stats_for(p) for p in paths}
    STATS.write_text("/* generated by build.py — counts shown on the site home page */\n"
                     f"window.COURSE_STATS = {json.dumps(stats, indent=2)};\n", encoding="utf-8")
    print(f"\nwrote {STATS.name}: " + ", ".join(f"{p} {s['lessons']} lessons" for p, s in stats.items()))
    if failed:
        raise SystemExit(f"build failed for: {', '.join(failed)}")


if __name__ == "__main__":
    main(sys.argv[1:])
